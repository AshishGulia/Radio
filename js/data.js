  getAll() {
    return this.stations;
  },

  getById(id) {
    return this.stations.find(s => s.id === parseInt(id));
  },

  getByCountry(country) {
    if (!country) return this.stations;
    return this.stations.filter(s => s.country && s.country.toLowerCase() === country.toLowerCase());
  },

  getByCategory(category) {
    if (!category) return this.stations;
    return this.stations.filter(s => s.category && s.category.some(c => c.toLowerCase() === category.toLowerCase()));
  },

  getPopular() {
    return this.stations.filter((_, i) => i % 3 === 0);
  },

  search(query) {
    if (!query) return this.stations;
    const q = query.toLowerCase().trim();
    return this.stations.filter(s => {
      const np = this.nowPlayingData && this.nowPlayingData[s.id];
      const songMatch = np && (np.song.toLowerCase().includes(q) || np.artist.toLowerCase().includes(q));
      return (
        s.name.toLowerCase().includes(q) ||
        s.city.toLowerCase().includes(q) ||
        s.country.toLowerCase().includes(q) ||
        (s.freq && s.freq.toLowerCase().includes(q)) ||
        (s.description && s.description.toLowerCase().includes(q)) ||
        (s.category && s.category.some(c => c.toLowerCase().includes(q))) ||
        songMatch
      );
    });
  }
